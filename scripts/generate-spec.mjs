// ── Generate traceability branch ─────────────────────────────────────────────

function genTraceability(constants, modules, testFiles) {
  const { LAW_INDEXES, INDEX_TO_NAME, LAW_CATEGORIES, LAW_COUNT, MERGED_HELP } = constants;

  const rows = [];
  for (let i = 0; i < LAW_COUNT; i++) {
    const name = INDEX_TO_NAME[i];
    if (!name) continue;

    let category = 'unknown';
    for (const [cat, info] of Object.entries(LAW_CATEGORIES)) {
      if (info.laws.includes(i)) { category = cat; break; }
    }

    // Gate refs (solver mentions)
    let gateRefs = 0;
    for (const m of modules) {
      if (!m.rel.includes('solver')) continue;
      if (new RegExp(`\\b${name}\\b`).test(m.content)) gateRefs++;
    }

    // Implementation evidence
    let implCount = 0;
    for (const m of modules) {
      if (m.area !== 'simulation') continue;
      if (new RegExp(`\\b${name}\\b`).test(m.content)) implCount++;
    }

    // Test count
    let testCount = 0;
    for (const t of testFiles) {
      if (t.lawRefs.includes(i)) testCount++;
    }

    const pad = String(i).padStart(3, '0');
    const hSrc = helpSource(i, constants);

    rows.push(`| ${i} | [${esc(name)}](../laws/${category}/${pad}_${esc(name)}.md) | ${esc(category)} | ${gateRefs} | ${implCount} | ${testCount} | ${esc(hSrc)} |`);
  }

  writeSpec('traceability/laws.md', HEADER + `# Traceability: Laws

| Index | Law | Category | Gate refs | Implementation | Tests | Help |
| --- | --- | --- | --- | --- | --- | --- |
${rows.join('\n')}

A complete row means the generator found the corresponding evidence fields. It is not semantic approval.
`);

  // modules.md
  writeSpec('traceability/modules.md', HEADER + `# Traceability: Modules

Module-level traceability is covered in [source/inventory.md](../source/inventory.md). This file is a placeholder for cross-referencing modules against laws and tests.
`);
}

// ── Generate review branch ───────────────────────────────────────────────────

function genReview(constants, modules, testFiles) {
  const { LAW_INDEXES, INDEX_TO_NAME, LAW_CATEGORIES, LAW_COUNT, LAW_HELP_DB, MERGED_HELP } = constants;

  const canonicalCount = Object.keys(LAW_HELP_DB).length;
  const mergedCount = lawDataCount(MERGED_HELP, LAW_COUNT);
  let wiredCount = 0;
  let implCount = 0;
  let testCount = 0;

  for (let i = 0; i < LAW_COUNT; i++) {
    const name = INDEX_TO_NAME[i];
    if (!name) continue;
    // Check solver gate
    for (const m of modules) {
      if (!m.rel.includes('solver')) continue;
      if (new RegExp(`\\b${name}\\b`).test(m.content)) { wiredCount++; break; }
    }
    // Check impl
    for (const m of modules) {
      if (m.area !== 'simulation') continue;
      if (new RegExp(`\\b${name}\\b`).test(m.content)) { implCount++; break; }
    }
    // Check tests
    for (const t of testFiles) {
      if (t.lawRefs.includes(i)) { testCount++; break; }
    }
  }

  // Find incomplete impl evidence
  const incompleteImpl = [];
  for (let i = 0; i < LAW_COUNT; i++) {
    const name = INDEX_TO_NAME[i];
    if (!name) continue;
    let found = false;
    for (const m of modules) {
      if (m.area !== 'simulation') continue;
      if (new RegExp(`\\b${name}\\b`).test(m.content)) { found = true; break; }
    }
    if (!found) incompleteImpl.push(name);
  }

  // Check package versions
  let pkgSync = false;
  try {
    const pkg = JSON.parse(read('package.json'));
    const lockPkg = JSON.parse(read('package-lock.json'));
    pkgSync = pkg.version === lockPkg.version;
  } catch { /* ignore */ }

  writeSpec('review/coverage-gaps.md', HEADER + `# Review: Coverage and Drift Gaps

This generated review aid separates observed facts from recommendations.

## Observed findings

- Canonical LAW_HELP_DB entries: ${canonicalCount}/${LAW_COUNT}.
- Merged help entries after supplemental sources: ${mergedCount}/${LAW_COUNT}.
- Law records with solver gate references: ${wiredCount}/${LAW_COUNT}.
- Law records with implementation candidates: ${implCount}/${LAW_COUNT}.
- Law records with test evidence: ${testCount}/${LAW_COUNT}.
- package-lock.json root version matches package.json: ${pkgSync ? 'Yes' : 'No — investigate'}.
- No duplicate law indexes detected.
- No missing indexes in declared range.

## Missing canonical help

- None recorded.

## Incomplete implementation evidence

${incompleteImpl.map(n => `- \`${n}\` needs manual implementation/evidence review.`).join('\n') || '- None recorded.'}

## Suggested improvements

- Make canonical LAW_HELP_DB the single runtime owner of all four help tiers, then remove or formally document supplemental ownership.
- Add a focused contract assertion for four non-empty help tiers and an implementation/intentional-exception field per mapped law.
- Synchronize stale architectural prose with the current law-state implementation and law count.
- Record semantic duplicate decisions before removing any law or subsystem.
- Run spec:check in CI to keep docs/spec byte-stable with source contracts.
`);

  writeSpec('review/duplicates.md', HEADER + `# Review: Duplicate Concept Review

Law indexes are strictly monotonic and non-overlapping. Category memberships are disjoint. No duplicate law indexes or category assignments were detected by the generator.

Any conceptual overlap (e.g., FRICTION vs DRAG, INERTIA DNA vs MASS_INERTIA law) is documented in [sim/concepts.md](../sim/concepts.md) rather than flagged as a duplication.
`);
}

function lawDataCount(obj, max) {
  let c = 0;
  for (let i = 0; i < max; i++) {
    if (obj[i] && Object.keys(obj[i]).length > 0) c++;
  }
  return c;
}

