// ── Generate laws branch ─────────────────────────────────────────────────────

function genLaws(constants, modules, testFiles, auditFiles) {
  const { LAW_INDEXES, INDEX_TO_NAME, LAW_CATEGORIES, LAW_PARAMETERS, MERGED_HELP, LAW_HELP_DB, LAW_HELP_PATCHES, MECHANICS_HELP, LAW_COUNT } = constants;

  // Build per-law data
  const lawData = [];
  for (let i = 0; i < LAW_COUNT; i++) {
    const name = INDEX_TO_NAME[i];
    if (!name) continue;

    // Find category
    let category = 'unknown';
    let color = 'GRAY';
    for (const [cat, info] of Object.entries(LAW_CATEGORIES)) {
      if (info.laws.includes(i)) { category = cat; color = info.color; break; }
    }

    // Find implementation evidence
    const impls = [];
    for (const m of modules) {
      if (m.area !== 'simulation') continue;
      const pat = new RegExp(`\\b${name}\\b`);
      if (pat.test(m.content)) impls.push(m.rel);
    }

    // Gate references (solver dispatches)
    const gateRefs = new Set();
    for (const m of modules) {
      if (!m.rel.includes('solver')) continue;
      const pat = new RegExp(`\\b${name}\\b`);
      if (pat.test(m.content)) gateRefs.add(m.rel);
    }

    // Test evidence
    const testRefs = [];
    for (const t of testFiles) {
      if (t.lawRefs.includes(i)) testRefs.push(t.rel);
    }

    // Audit evidence
    const auditRefs = [];
    for (const a of auditFiles) {
      if (a.lawRefs.includes(i)) auditRefs.push(a.rel);
    }

    const status = determineStatus(i, name, impls, gateRefs.size);
    const hSource = helpSource(i, constants);
    const params = LAW_PARAMETERS[i] || [];

    lawData.push({
      idx: i, name, category, color, status,
      impls, gateRefs: gateRefs.size,
      testRefs, auditRefs,
      helpSource: hSource, params,
    });
  }

  // laws/index.md
  const catRows = Object.entries(LAW_CATEGORIES)
    .map(([cat, info]) => {
      const solverWired = lawData.filter(l => l.category === cat && l.gateRefs > 0).length;
      const merged = lawData.filter(l => l.category === cat && MERGED_HELP[l.idx] && Object.keys(MERGED_HELP[l.idx]).length > 0).length;
      return `| ${esc(cat.charAt(0).toUpperCase() + cat.slice(1))} | ${esc(info.color)} | ${info.laws.length} | ${solverWired} | ${merged} |`;
    })
    .join('\n');

  const totalMapped = lawData.length;
  const canonicalHelp = Object.keys(LAW_HELP_DB).length;
  const mergedHelp = lawData.filter(l => MERGED_HELP[l.idx] && Object.keys(MERGED_HELP[l.idx]).length > 0).length;

  writeSpec('laws/index.md', HEADER + `# Laws: Index

The law catalog is generated from LAW_INDEXES, LAW_CATEGORIES and associated metadata in [src/constants.js](${relToRoot('src/constants.js')}). There are \`${totalMapped}\` mapped records across \`${Object.keys(LAW_CATEGORIES).length}\` categories.

## Category coverage

| Category | Color | Count | Solver-wired records | Merged help records |
| --- | --- | --- | --- | --- |
${catRows}

## Contract findings

- Canonical LAW_HELP_DB entries: ${canonicalHelp}/${totalMapped}.
- Merged help entries after supplemental sources: ${mergedHelp}/${totalMapped}.
- Every mapped law has merged help evidence.
- Every category overview links to one generated record per law index.

## Category branches

${Object.keys(LAW_CATEGORIES).map(cat => `- [${esc(cat.charAt(0).toUpperCase() + cat.slice(1))}](categories/${cat}/overview.md)`).join('\n')}
`);

  // Per-category overview
  for (const [cat, info] of Object.entries(LAW_CATEGORIES)) {
    const catLaws = lawData.filter(l => l.category === cat);
    const rows = catLaws.map(l => {
      const pad = String(l.idx).padStart(3, '0');
      return `| ${l.idx} | [${esc(l.name)}](../../${cat}/${pad}_${esc(l.name)}.md) | ${esc(l.status)} | ${esc(l.helpSource)} | ${esc(l.impls.length > 0 ? l.impls[0] : 'not found')} |`;
    }).join('\n');

    writeSpec(`laws/categories/${cat}/overview.md`, HEADER + `# Laws: ${esc(cat.charAt(0).toUpperCase() + cat.slice(1))}

- Color: \`${esc(info.color)}\`
- Mapped count: \`${info.laws.length}\`
- Declared roster: \`${info.laws.join(', ')}\`

| Index | Law | Status | Help | Implementation |
| --- | --- | --- | --- | --- |
${rows}

The category roster is a classification contract. Behavior evidence is in individual records and [traceability/laws.md](../../../traceability/laws.md).
`);
  }

  // Per-law records
  for (const l of lawData) {
    const pad = String(l.idx).padStart(3, '0');
    const help = MERGED_HELP[l.idx] || {};

    const testLinks = l.testRefs.length > 0
      ? l.testRefs.map(r => `[${r}](${relToRoot(r)})`).join(', ')
      : 'No test file mentions this law name.';
    const auditLinks = l.auditRefs.length > 0
      ? l.auditRefs.map(r => `[${relToRoot(r)}](${relToRoot(r)})`).join(', ')
      : 'No filename-matched audit record found.';
    const implLinks = l.impls.length > 0
      ? l.impls.map(r => `[${r}](${relToRoot(r)})`).join(', ')
      : 'No implementation file found.';

    const helpRows = ['hint', 'explanation', 'system', 'advanced'].map(tier => {
      const val = help[tier] || 'MISSING';
      return `| ${tier.toUpperCase()} | ${esc(val)} |`;
    }).join('\n');

    const paramStr = l.params.length > 0
      ? l.params.map(p => `\`${esc(p)}\``).join(', ')
      : 'No parameter mapping recorded.';

    writeSpec(`laws/${l.category}/${pad}_${l.name}.md`, HEADER + `# Law ${l.idx}: ${esc(l.name)}

| Property | Observed value |
| --- | --- |
| Index | ${l.idx} |
| Category | ${esc(l.category)} |
| Color | ${esc(l.color)} |
| Status | ${esc(l.status)} |
| Solver gate references | ${l.gateRefs} |
| Help source | ${esc(l.helpSource)} |

## Parameters

${paramStr}

## Four-tier help

| Tier | Content |
| --- | --- |
${helpRows}

## Implementation evidence

${implLinks}

## Verification evidence

- Tests: ${testLinks}
- Audits: ${auditLinks}

## Interpretation boundary

This record confirms classification, metadata and text-level source evidence. It does not assert physical fidelity, conservation, balance, or non-redundancy. Those claims require targeted tests and review against [src/physics/lawgroups/SPEC.md](${relToRoot('src/physics/lawgroups/SPEC.md')}).
`);
  }
}

// ── Generate source branch ───────────────────────────────────────────────────

function genSource(modules) {
  const areas = {};
  for (const m of modules) {
    if (!areas[m.area]) areas[m.area] = { files: 0, exports: 0, lawRefs: 0 };
    areas[m.area].files++;
    areas[m.area].exports += m.exportCount;
    areas[m.area].lawRefs += m.lawRefCount;
  }

  const areaRows = Object.entries(areas)
    .sort((a, b) => a[0].localeCompare(b[0]))
    .map(([a, v]) => `| ${esc(a.charAt(0).toUpperCase() + a.slice(1))} | ${v.files} | ${v.exports} | ${v.lawRefs} |`)
    .join('\n');

  const moduleRows = modules
    .sort((a, b) => a.rel.localeCompare(b.rel))
    .map(m => `| [${m.rel}](${relToRoot(m.rel)}) | ${esc(m.area)} | ${m.lineCount} | ${m.exportCount} | ${m.importCount} | ${m.lawRefCount} |`)
    .join('\n');

  writeSpec('source/inventory.md', HEADER + `# Source: Inventory

The generator scanned \`${modules.length}\` files from active repository inputs. Individual module records are under [source/modules/](modules/).

| Area | Files | Exports | Law references |
| --- | --- | --- | --- |
${areaRows}

## Module list

| Path | Area | Lines | Exports | Imports | Law refs |
| --- | --- | --- | --- | --- | --- |
${moduleRows}
`);
}

