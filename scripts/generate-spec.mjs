#!/usr/bin/env node
// scripts/generate-spec.mjs — VEPA4 deterministic spec generator
// Reads live source contracts and produces docs/spec/ artefacts.
// No runtime dependencies — Node built-ins only.
// Usage: node scripts/generate-spec.mjs [--check]

import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync, existsSync } from 'node:fs';
import { join, relative, dirname, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(fileURLToPath(import.meta.url)) + '/..';
const SPEC_DIR = join(ROOT, 'docs', 'spec');
const CHECK_MODE = process.argv.includes('--check');
const HEADER = '<!-- Generated by scripts/generate-spec.mjs; do not edit. -->\n\n';

// ── Helpers ──────────────────────────────────────────────────────────────────

function read(rel) {
  return readFileSync(join(ROOT, rel), 'utf8');
}

function readLines(rel) {
  return read(rel).split('\n');
}

function writeSpec(rel, content) {
  const full = join(SPEC_DIR, rel);
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, content, 'utf8');
}

function walkDir(dir, filter) {
  const results = [];
  if (!existsSync(dir)) return results;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const fp = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === 'node_modules' || entry.name === '.dist') continue;
      results.push(...walkDir(fp, filter));
    } else if (!filter || filter(fp)) {
      results.push(fp);
    }
  }
  return results;
}

function relFromSpec(fp) {
  return relative(SPEC_DIR, fp).split(sep).join('/');
}

function relToRoot(fp) {
  return relative(ROOT, fp).split(sep).join('/');
}

function esc(s) {
  return String(s).replace(/\|/g, '\\|');
}

// ── Parse constants.js ───────────────────────────────────────────────────────

function parseConstants() {
  const src = read('src/constants.js');
  const fullSrc = src + '\n' + read('src/physics/lawgroups/mechanicsHelp.js');

  // Extract PARTICLE_STRIDE
  const strideMatch = src.match(/PARTICLE_STRIDE\s*=\s*(\d+)/);
  const PARTICLE_STRIDE = strideMatch ? Number(strideMatch[1]) : 100;

  // Extract DNA_COUNT
  const dnaCountMatch = src.match(/DNA_COUNT\s*=\s*(\d+)/);
  const DNA_COUNT = dnaCountMatch ? Number(dnaCountMatch[1]) : 64;

  // Extract LAW_COUNT
  const lawCountMatch = src.match(/LAW_COUNT\s*=\s*(\d+)/);
  const LAW_COUNT = lawCountMatch ? Number(lawCountMatch[1]) : 136;

  // Extract LAW_INDEXES name→value pairs
  const LAW_INDEXES = {};
  const lawIdxRe = /(\w+):\s*(\d+)/g;
  const lawIdxBlock = src.match(/export const LAW_INDEXES\s*=\s*\{([\s\S]*?)\};/);
  if (lawIdxBlock) {
    let m;
    while ((m = lawIdxRe.exec(lawIdxBlock[1]))) {
      LAW_INDEXES[m[1]] = Number(m[2]);
    }
  }
  const INDEX_TO_NAME = {};
  for (const [name, idx] of Object.entries(LAW_INDEXES)) INDEX_TO_NAME[idx] = name;

  // Extract LAW_CATEGORIES — we need to resolve LAW_INDEXES.X references
  const LAW_CATEGORIES = {};
  const catBlock = src.match(/export const LAW_CATEGORIES\s*=\s*\{([\s\S]*?)\n\};/);
  if (catBlock) {
    const catRe = /(\w+):\s*\{\s*color:\s*'(\w+)',\s*laws:\s*\[([\s\S]*?)\]/g;
    let cm;
    while ((cm = catRe.exec(catBlock[1]))) {
      const catName = cm[1];
      const color = cm[2];
      const lawRefs = cm[3];
      const lawNums = [];
      const refRe = /LAW_INDEXES\.(\w+)/g;
      let rm;
      while ((rm = refRe.exec(lawRefs))) {
        if (LAW_INDEXES[rm[1]] !== undefined) lawNums.push(LAW_INDEXES[rm[1]]);
      }
      LAW_CATEGORIES[catName] = { color, laws: lawNums };
    }
  }

  // Extract LAW_PARAMETERS
  const LAW_PARAMETERS = {};
  const paramBlock = src.match(/export const LAW_PARAMETERS\s*=\s*\{([\s\S]*?)\n\};/);
  if (paramBlock) {
    const paramRe = /\[LAW_INDEXES\.(\w+)\]:\s*\[([^\]]*)\]/g;
    let pm;
    while ((pm = paramRe.exec(paramBlock[1]))) {
      const idx = LAW_INDEXES[pm[1]];
      if (idx !== undefined) {
        LAW_PARAMETERS[idx] = pm[2].split(',').map(s => s.trim().replace(/^['"]|['"]$/g, ''));
      }
    }
  }

  // Extract LAW_HELP_DB
  const LAW_HELP_DB = {};
  const helpBlock = src.match(/export const LAW_HELP_DB\s*=\s*\{([\s\S]*?)\n\};/);
  if (helpBlock) {
    const helpRe = /\[(\d+)\]:\s*\{([^}]*)\}/g;
    let hm;
    while ((hm = helpRe.exec(helpBlock[1]))) {
      const idx = Number(hm[1]);
      const fields = {};
      const tierRe = /(\w+):\s*'([^']*)'/g;
      let tm;
      while ((tm = tierRe.exec(hm[2]))) {
        fields[tm[1].toLowerCase()] = tm[2];
      }
      LAW_HELP_DB[idx] = fields;
    }
  }

  // Extract LAW_HELP_PATCHES (supplemental help)
  const LAW_HELP_PATCHES = {};
  const patchSrc = existsSync(join(ROOT, 'src/state/lawHelpPatches.js')) ? read('src/state/lawHelpPatches.js') : '';
  if (patchSrc) {
    const patchBlock = patchSrc.match(/export const LAW_HELP_PATCHES\s*=\s*\{([\s\S]*?)\n\};/);
    if (patchBlock) {
      const patchRe = /\[(\d+)\]:\s*\{([^}]*)\}/g;
      let pm2;
      while ((pm2 = patchRe.exec(patchBlock[1]))) {
        const idx = Number(pm2[1]);
        const fields = {};
        const tierRe = /(\w+):\s*'([^']*)'/g;
        let tm;
        while ((tm = tierRe.exec(pm2[2]))) {
          fields[tm[1].toLowerCase()] = tm[2];
        }
        LAW_HELP_PATCHES[idx] = fields;
      }
    }
  }

  // Merge help: canonical + patches
  const MERGED_HELP = {};
  for (const idx of Object.keys(LAW_HELP_DB).map(Number)) {
    MERGED_HELP[idx] = { ...LAW_HELP_DB[idx] };
  }
  for (const idx of Object.keys(LAW_HELP_PATCHES).map(Number)) {
    if (!MERGED_HELP[idx]) MERGED_HELP[idx] = {};
    for (const [k, v] of Object.entries(LAW_HELP_PATCHES[idx])) {
      if (!MERGED_HELP[idx][k] || MERGED_HELP[idx][k] === 'MISSING') MERGED_HELP[idx][k] = v;
    }
  }

  // MECHANICS_HELP from mechanicsHelp.js
  const MECHANICS_HELP = {};
  const mechHelpBlock = fullSrc.match(/export const MECHANICS_HELP\s*=\s*\{([\s\S]*?)\n\};/);
  if (mechHelpBlock) {
    const mhRe = /(\w+):\s*\{([^}]*)\}/g;
    let mhm;
    while ((mhm = mhRe.exec(mechHelpBlock[1]))) {
      const name = mhm[1];
      const idx = LAW_INDEXES[name];
      if (idx !== undefined) {
        const fields = {};
        const fRe = /(\w+):\s*'([^']*)'/g;
        let fm;
        while ((fm = fRe.exec(mhm[2]))) {
          fields[fm[1].toLowerCase()] = fm[2];
        }
        MECHANICS_HELP[idx] = fields;
      }
    }
  }

  // Merge MECHANICS_HELP into MERGED_HELP
  for (const [idxStr, fields] of Object.entries(MECHANICS_HELP)) {
    const idx = Number(idxStr);
    if (!MERGED_HELP[idx]) MERGED_HELP[idx] = {};
    for (const [k, v] of Object.entries(fields)) {
      if (!MERGED_HELP[idx][k] || MERGED_HELP[idx][k] === 'MISSING') MERGED_HELP[idx][k] = v;
    }
  }

  return {
    PARTICLE_STRIDE, DNA_COUNT, LAW_COUNT,
    LAW_INDEXES, INDEX_TO_NAME,
    LAW_CATEGORIES, LAW_PARAMETERS, LAW_HELP_DB, LAW_HELP_PATCHES,
    MERGED_HELP, MECHANICS_HELP,
  };
}

// ── Source scanning ──────────────────────────────────────────────────────────

function classifyFile(fp) {
  const r = relative(ROOT, fp);
  if (r.startsWith('src/physics/') || r.startsWith('src/spawn/') || r.startsWith('src/worker/')) return 'simulation';
  if (r.startsWith('src/ui/')) return 'ui';
  if (r.startsWith('src/state/') || r.startsWith('src/dna/')) return 'state';
  if (r.startsWith('tests/')) return 'testing';
  if (r.startsWith('bench/')) return 'benchmark';
  if (r.startsWith('docs/')) return 'documentation';
  if (r.startsWith('audit-suite/')) return 'documentation';
  if (r.startsWith('exports/')) return 'documentation';
  if (r === 'package.json' || r === 'package-lock.json' || r === 'vite.config.js' || r === 'vitest.config.js' || r === 'vercel.json' || r === 'index.html' || r === 'style.css') return 'repository';
  if (r.startsWith('scripts/')) return 'runtime';
  return 'application';
}

function scanSourceFiles(LAW_INDEXES) {
  const files = walkDir(ROOT, fp => {
    const ext = fp.split('.').pop();
    return ['js', 'mjs', 'json', 'html', 'css'].includes(ext) && !fp.includes('node_modules') && !fp.includes('.dist');
  });

  const modules = files.map(fp => {
    const rel = relToRoot(fp);
    let content = '';
    try { content = readFileSync(fp, 'utf8'); } catch { return null; }
    const lines = content.split('\n');
    const lineCount = lines.length;

    // Count exports
    const exportMatches = content.match(/\bexport\s+(default\s+)?(function|class|const|let|var|async)\s+\w+/g) || [];
    const exportDefault = content.match(/\bexport\s+default\b/g) || [];
    const exportNames = content.match(/\bexport\s+\{([^}]+)\}/g) || [];
    const exportCount = exportMatches.length + exportDefault.length + exportNames.length;

    // Count imports
    const importMatches = content.match(/\bimport\s+/g) || [];
    const importCount = importMatches.length;

    // Law references
    const lawRefs = new Set();
    for (const [name, idx] of Object.entries(LAW_INDEXES)) {
      if (content.includes(name)) lawRefs.add(idx);
    }

    const area = classifyFile(fp);

    return {
      rel, area, lineCount, exportCount, importCount,
      lawRefCount: lawRefs.size,
      lawRefs: [...lawRefs].sort((a, b) => a - b),
      content,
    };
  }).filter(Boolean);

  return modules;
}

function scanTestFiles(LAW_INDEXES) {
  const testFiles = walkDir(ROOT, fp => fp.endsWith('.test.js') || fp.endsWith('.spec.js'));
  const results = [];

  for (const fp of testFiles) {
    const rel = relToRoot(fp);
    let content = '';
    try { content = readFileSync(fp, 'utf8'); } catch { continue; }
    const lawRefs = new Set();
    for (const [name, idx] of Object.entries(LAW_INDEXES)) {
      if (content.includes(name)) lawRefs.add(idx);
    }
    results.push({ rel, lawRefs: [...lawRefs] });
  }

  return results;
}

